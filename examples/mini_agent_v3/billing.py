class QuotaExceeded(PermissionError):
    def __init__(self, tenant_id: str, limit: float, spent: float):
        super().__init__(
            "tenant %s 已用 %.4f USD，超过配额 %.4f" % (tenant_id, spent, limit)
        )
        self.tenant_id = tenant_id
        self.limit = limit
        self.spent = spent


class Quota:
    """Pre-call quota check.  Post-hoc billing is not a quota."""

    def __init__(self, ledger: Ledger, monthly_limits: Optional[Dict[str, float]] = None,
                 default_limit: float = 50.0):
        self.ledger = ledger
        self.monthly_limits = dict(monthly_limits or {})
        self.default_limit = default_limit

    def check(self, tenant_id: str) -> None:
        limit = self.monthly_limits.get(tenant_id, self.default_limit)
        spent = self.ledger.total_by_tenant().get(tenant_id, 0.0)
        if spent >= limit:
            raise QuotaExceeded(tenant_id, limit, spent)
