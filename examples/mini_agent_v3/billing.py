"""Metering and a billing ledger.

The contract that matters is **idempotency**: a retried call must not be billed
twice.  That is what ``idempotency_key`` is for, and it must be generated by the
gateway/pipeline, never by the model.

Second contract: **the ledger is append-only**.  Refunds and corrections are new
records (``reversal_of``), so the history of what was billed stays auditable.

Numbers here are illustrative prices.  The lesson is the shape of the event and
the duplicate-suppression rule, not the rates.
"""
from __future__ import annotations

import time
import uuid
from dataclasses import asdict, dataclass, field
from typing import Dict, List, Optional

# price per 1M tokens: (input, cached_input, output)
PRICE_TABLE: Dict[str, Dict[str, float]] = {
    "gpt-4.1-mini": {"input": 0.40, "cached_input": 0.10, "output": 1.60},
    "gpt-4.1": {"input": 2.00, "cached_input": 0.50, "output": 8.00},
    "reasoning-large": {"input": 3.00, "cached_input": 0.75, "output": 12.00},
    "small-classifier": {"input": 0.10, "cached_input": 0.02, "output": 0.20},
}
DEFAULT_PRICE = {"input": 1.0, "cached_input": 0.25, "output": 4.0}


def price_for(model: str) -> Dict[str, float]:
    return PRICE_TABLE.get(model, DEFAULT_PRICE)


@dataclass
class UsageEvent:
    """One billable unit of work.  Mirrors ``templates/usage_event.json``."""

    tenant_id: str
    kind: str  # llm | tool | sandbox | retrieval
    model: str = ""
    input_tokens: int = 0
    cached_tokens: int = 0
    output_tokens: int = 0
    tool_name: str = ""
    tool_calls: int = 0
    sandbox_seconds: float = 0.0
    cost_usd: float = 0.0
    idempotency_key: str = ""
    request_id: str = ""
    task_id: str = ""
    agent_id: str = ""
    user_id: str = ""
    retry_of: Optional[str] = None
    reversal_of: Optional[str] = None
    occurred_at: float = field(default_factory=time.time)
    event_id: str = field(default_factory=lambda: "evt_" + uuid.uuid4().hex[:12])

    def to_dict(self) -> Dict[str, object]:
        return asdict(self)


def compute_llm_cost(
    model: str,
    *,
    input_tokens: int,
    cached_tokens: int = 0,
    output_tokens: int = 0,
) -> float:
    """Cached tokens are priced separately — forgetting this over-bills.

    Note we bill *uncached* input at the input rate: ``cached_tokens`` is the
    subset of ``input_tokens`` that hit the cache, not an extra charge.
    """
    price = price_for(model)
    uncached = max(0, input_tokens - cached_tokens)
    return (
        uncached / 1_000_000 * price["input"]
        + cached_tokens / 1_000_000 * price["cached_input"]
        + output_tokens / 1_000_000 * price["output"]
    )


def to_usage_event(
    *,
    tenant_id: str,
    model: str,
    usage: Dict[str, int],
    request_id: str,
    seq: int,
    task_id: str = "",
    agent_id: str = "",
    user_id: str = "",
    retry_of: Optional[str] = None,
) -> UsageEvent:
    """Build a metering event with a host-generated idempotency key."""
    input_tokens = int(usage.get("input_tokens", 0) or 0)
    cached = int(usage.get("cached_tokens", 0) or 0)
    output = int(usage.get("output_tokens", 0) or 0)
    if input_tokens == 0 and output == 0:
        total = int(usage.get("total_tokens", 0) or 0)
        input_tokens = total
    return UsageEvent(
        tenant_id=tenant_id,
        kind="llm",
        model=model,
        input_tokens=input_tokens,
        cached_tokens=cached,
        output_tokens=output,
        cost_usd=compute_llm_cost(
            model, input_tokens=input_tokens, cached_tokens=cached, output_tokens=output
        ),
        idempotency_key=f"{request_id}:llm:{seq}",
        request_id=request_id,
        task_id=task_id,
        agent_id=agent_id,
        user_id=user_id,
        retry_of=retry_of,
    )


class Ledger:
    """Append-only usage ledger with duplicate suppression and reporting."""

    def __init__(self, path: Optional[str] = None):
        import json
        from pathlib import Path

        self._path = Path(path) if path else None
        self._events: List[UsageEvent] = []
        self._seen_keys: set = set()
        self.duplicates = 0
        if self._path and self._path.exists():
            import json as _json

            for row in _json.loads(self._path.read_text(encoding="utf-8")):
                event = UsageEvent(**row)
                self._events.append(event)
                self._seen_keys.add(event.idempotency_key)

    # -- write -----------------------------------------------------------

    def record(self, event: UsageEvent) -> bool:
        """Append unless the idempotency key was already used.

        Returns False for a duplicate — callers must treat that as success, not
        as an error: the work is already accounted for.
        """
        if not event.idempotency_key:
            raise ValueError("usage event requires an idempotency_key")
        if event.idempotency_key in self._seen_keys:
            self.duplicates += 1
            return False
        self._seen_keys.add(event.idempotency_key)
        self._events.append(event)
        self._flush()
        return True

    def reverse(self, event_id: str, reason: str = "") -> UsageEvent:
        original = next((e for e in self._events if e.event_id == event_id), None)
        if original is None:
            raise KeyError(event_id)
        reversal = UsageEvent(
            tenant_id=original.tenant_id,
            kind=original.kind,
            model=original.model,
            cost_usd=-original.cost_usd,
            idempotency_key=f"reversal:{event_id}",
            request_id=original.request_id,
            task_id=original.task_id,
            reversal_of=event_id,
            tool_name=reason,
        )
        self.record(reversal)
        return reversal

    # -- read ------------------------------------------------------------

    def events(self) -> List[UsageEvent]:
        return list(self._events)

    def total_by_tenant(self) -> Dict[str, float]:
        totals: Dict[str, float] = {}
        for event in self._events:
            totals[event.tenant_id] = round(
                totals.get(event.tenant_id, 0.0) + event.cost_usd, 6
            )
        return totals

    def total_for_request(self, request_id: str) -> float:
        return round(
            sum(e.cost_usd for e in self._events if e.request_id == request_id), 6
        )

    def answer_three_questions(self) -> Dict[str, object]:
        """The three questions from the roadmap's step 6."""
        by_model: Dict[str, float] = {}
        for event in self._events:
            if event.model:
                by_model[event.model] = round(by_model.get(event.model, 0.0) + event.cost_usd, 6)
        return {
            "这个月哪个租户花了多少钱": self.total_by_tenant(),
            "按模型的成本分布": by_model,
            "重复计费拦截次数": self.duplicates,
            "事件数": len(self._events),
        }

    def _flush(self) -> None:
        if not self._path:
            return
        import json

        self._path.parent.mkdir(parents=True, exist_ok=True)
        payload = [e.to_dict() for e in self._events]
        self._path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


